import Foundation
import CoreBluetooth

/// Shared BLE contract used by both targets.
///
/// Basic idea: BLE devices communicate through services and characteristics.
/// A service is a group of related values. A characteristic is one readable,
/// writable, or notifiable value inside that service.
enum BLEUUIDs {
    /// Main service advertised by the peripheral and scanned by the central.
    static let deviceLabService = CBUUID(string: "A1000001-0000-1000-8000-00805F9B34FB")

    /// Notifiable sensor-style payload sent from peripheral to central.
    static let telemetry = CBUUID(string: "A1000002-0000-1000-8000-00805F9B34FB")

    /// Writable command endpoint used by the central.
    static let command = CBUUID(string: "A1000003-0000-1000-8000-00805F9B34FB")

    /// Read/write configuration endpoint for settings such as reporting interval.
    static let configuration = CBUUID(string: "A1000004-0000-1000-8000-00805F9B34FB")

    /// Read-only metadata endpoint for name, firmware, and manufacturer.
    static let deviceInfo = CBUUID(string: "A1000005-0000-1000-8000-00805F9B34FB")
}

/// Commands that the central app can write to the peripheral.
///
/// A typed enum is safer than scattering raw strings throughout the app because
/// the compiler can catch missing cases and typos.
enum DeviceLabCommand: String, CaseIterable, Identifiable {
    case ping = "PING"
    case identify = "IDENTIFY"
    case resetCounter = "RESET_COUNTER"

    var id: String { rawValue }

    /// Human-readable text shown in SwiftUI buttons.
    var title: String {
        switch self {
        case .ping:
            return "Ping"
        case .identify:
            return "Identify"
        case .resetCounter:
            return "Reset Counter"
        }
    }

    /// BLE writes use bytes, so each command converts itself into UTF-8 data.
    var data: Data {
        Data(rawValue.utf8)
    }
}

/// Telemetry payload generated by the peripheral and rendered by the central.
///
/// Codable JSON is beginner-friendly because it is easy to log and inspect with
/// external BLE tools while still being strongly typed in Swift.
struct DeviceLabTelemetry: Codable, Equatable {
    let sequence: Int
    let batteryLevel: Int
    let temperatureCelsius: Double
    let uptimeSeconds: Int
    let lastCommand: String

    /// Encodes this Swift model into bytes for a BLE characteristic value.
    var encoded: Data? {
        try? JSONEncoder().encode(self)
    }

    /// Decodes bytes read from BLE back into a Swift model.
    static func decode(from data: Data) -> DeviceLabTelemetry? {
        try? JSONDecoder().decode(DeviceLabTelemetry.self, from: data)
    }
}

/// Static information about the peripheral device.
struct DeviceLabPeripheralInfo: Codable, Equatable {
    let name: String
    let firmwareVersion: String
    let manufacturer: String

    var encoded: Data? {
        try? JSONEncoder().encode(self)
    }

    static func decode(from data: Data) -> DeviceLabPeripheralInfo? {
        try? JSONDecoder().decode(DeviceLabPeripheralInfo.self, from: data)
    }
}
